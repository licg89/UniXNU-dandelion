// The code of one 16-bit half pattern: negatives and NaNs 0, values of 1.0 and above (and +infinity) 255.
inline uint8_t code(uint16_t bits,bool encoded) {
    if(bits&0x8000)return 0;
    if(bits>=0x7c00)return bits==0x7c00?255:0;
    const uint16_t *thresholds=encoded?kEncoded:kLinear;
    unsigned lo=0,hi=255;   // the number of thresholds at or below bits
    while(lo<hi){const unsigned mid=(lo+hi)/2;if(bits>=thresholds[mid])lo=mid+1;else hi=mid;}
    return uint8_t(lo);
}
